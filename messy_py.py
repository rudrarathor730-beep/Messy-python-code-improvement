SUBJECT_COUNT = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def sum_scores(record):
    total = 0
    for i in range(1, len(record)):
        total = total + record[i]
    return total


def average_score(record):
    return sum_scores(record) / SUBJECT_COUNT


def class_average(records):
    total = 0
    for record in records:
        total = total + average_score(record)
    return total / len(records)


def count_above_class_average(records):
    """Return how many students have an average above the class average."""
    average = class_average(records)
    count = 0
    for record in records:
        if average_score(record) > average:
            count = count + 1
    return count


print("REPORT")

for student in students:
    total = sum_scores(student)
    average = average_score(student)

    if average >= 90:
        grade = "A"
    elif average >= 80:
        grade = "B"
    elif average >= 70:
        grade = "C"
    elif average >= 60:
        grade = "D"
    else:
        grade = "F"

    print(f"{student[0]}{total}{average}{grade}")

print(f"Class average:{class_average(students)}")
print(f"Above class average:{count_above_class_average(students)}")

highest_average = 0
topper_name = ""

for student in students:
    average = average_score(student)

    if average > highest_average:
        highest_average = average
        topper_name = student[0]

print(f"Topper:{topper_name}{highest_average}")
